-- MissionWatch core schema (SRS §9). Later phases add users, watchlists,
-- notifications, model versions and predictions in new migrations.

create table provider (
    id           bigint generated by default as identity primary key,
    external_id  varchar not null unique,
    name         varchar not null,
    abbrev       varchar,
    country_code varchar,
    type         varchar
);

create table rocket (
    id          bigint generated by default as identity primary key,
    external_id varchar not null unique,
    name        varchar not null,
    family      varchar,
    variant     varchar,
    provider_id bigint references provider (id)
);

create table launch_site (
    id           bigint generated by default as identity primary key,
    external_id  varchar not null unique,
    name         varchar not null,
    location     varchar,
    country_code varchar,
    latitude     double precision,
    longitude    double precision
);

create table launch (
    id                bigint generated by default as identity primary key,
    external_id       varchar not null unique,
    name              varchar not null,
    mission_name      varchar not null,
    scheduled_time    timestamp(6) with time zone not null,
    status            varchar not null,
    provider_id       bigint not null references provider (id),
    rocket_id         bigint not null references rocket (id),
    site_id           bigint not null references launch_site (id),
    detail_level      varchar not null,
    source_updated_at timestamp(6) with time zone,
    refreshed_at      timestamp(6) with time zone not null,
    -- The normalised launch as served by the API (frontend Launch model).
    document          jsonb not null,
    -- The latest source record, kept for traceability and re-mapping.
    source_payload    jsonb not null
);

create index launch_scheduled_time_idx on launch (scheduled_time);
create index launch_status_idx on launch (status);
create index launch_provider_idx on launch (provider_id);

-- One row per observed change of a launch's schedule or status (FR-07).
create table launch_snapshot (
    id                bigint generated by default as identity primary key,
    launch_id         bigint not null references launch (id) on delete cascade,
    observed_at       timestamp(6) with time zone not null,
    scheduled_time    timestamp(6) with time zone not null,
    status            varchar not null,
    source            varchar not null,
    source_updated_at timestamp(6) with time zone
);

create index launch_snapshot_launch_idx on launch_snapshot (launch_id, observed_at);

-- Every refresh attempt, successful or not. Feeds data-freshness metadata.
create table data_refresh (
    id              bigint generated by default as identity primary key,
    source          varchar not null,
    job             varchar not null,
    started_at      timestamp(6) with time zone not null,
    finished_at     timestamp(6) with time zone not null,
    succeeded       boolean not null,
    records_stored  integer not null,
    records_skipped integer not null,
    message         varchar
);

create index data_refresh_source_idx on data_refresh (source, finished_at desc);
